export function roguelikePanelFromDocument(document) {
  const tasks = isPlainObject(document) && Array.isArray(document.tasks) ? document.tasks : []
  const task = tasks.find(item => isPlainObject(item) && item.type === 'Roguelike' && isPlainObject(item.params))
  if (!task) return null
  const panel = {}
  for (const [param, key] of Object.entries(PANEL_KEY_BY_PARAM)) {
    if (task.params[param] !== undefined) panel[key] = task.params[param]
  }
  return panel
}

// The confirmation panel URL-encodes every field value so spaces and punctuation
// survive the whitespace-separated `key=value` tokens it sends back
// (src/client/index.js confirmLine). Roguelike overrides skip the generic panel
// coercion in task-panel.js that decodes them, so a Chinese squad such as
// 蓝图测绘分队 arrives as 54 ASCII characters and trips the 1–32 length check.
function decodePanelValue(raw) {
  if (typeof raw !== 'string' || !/%[0-9A-Fa-f]{2}/u.test(raw)) return raw
  try { return decodeURIComponent(raw) } catch { return raw }
}

function coerceOverride(spec, raw, key, capabilities, pendingTheme) {
  const value = raw === undefined || raw === null ? '' : String(raw).trim()
  if (spec.kind === 'theme') {
    const ids = roguelikeThemeIds(capabilities)
    if (!ids.includes(value)) throw new Error(`肉鸽主题无效：${value || '(空)'}；当前 MAA 可选 ${ids.join(' / ')}`)
    return value
  }
  if (spec.kind === 'mode') {
    const theme = findRoguelikeTheme(capabilities, pendingTheme) ?? capabilities.roguelike.themes[0]
    const allowed = (theme?.modes ?? []).map(item => item.value)
    if (!/^\d+$/.test(value) || !allowed.includes(Number(value))) {
      throw new Error(`肉鸽模式无效：${value || '(空)'}；主题 ${theme?.id ?? '未知'} 可选 ${allowed.join(' / ')}`)
    }
    return Number(value)
  }
  // The panel offers MAX for difficulty: resolve it against the theme the plan
  // is actually about to run, so a human never has to remember the numbers.
  if (spec.kind === 'integer' && key === 'difficulty' && value.toUpperCase() === 'MAX') {
    const theme = findRoguelikeTheme(capabilities, pendingTheme) ?? capabilities.roguelike.themes[0]
    const values = (theme?.difficulties ?? []).filter(item => Number.isFinite(item))
    if (values.length === 0) throw new Error(`主题 ${theme?.id ?? '未知'} 没有可用难度`)
    return Math.max(...values)
  }
  if (spec.kind === 'integer') {
    if (!/^\d+$/.test(value)) throw new Error(`${ROGUELIKE_OVERRIDE_LABELS[key]}必须是整数`)
    const number = Number(value)
    if (number < spec.min || number > spec.max) throw new Error(`${ROGUELIKE_OVERRIDE_LABELS[key]}必须在 ${spec.min}–${spec.max} 之间`)
    return number
  }
  if (spec.kind === 'boolean') {
    if (!/^(?:true|false|1|0)$/i.test(value)) throw new Error(`${ROGUELIKE_OVERRIDE_LABELS[key]}只能是 true 或 false`)
    return value === 'true' || value === '1'
  }
  if (spec.optional && value === '') return undefined
  if (value.length < spec.min || value.length > spec.max) throw new Error(`${ROGUELIKE_OVERRIDE_LABELS[key]}长度必须在 ${spec.min}–${spec.max} 之间`)
  return value
}

export function generatedTaskPath(configDir) {
  if (typeof configDir !== 'string' || configDir.trim() === '' || !path.isAbsolute(configDir.trim())) {
    throw new TypeError('maa-cli config directory must be an absolute path')
  }
  return path.join(configDir.trim(), 'tasks', `${GENERATED_TASK_NAME}.json`)
}

export async function writeGeneratedTask(document, options = {}) {
  const target = generatedTaskPath(options.configDir)
  const tasksDir = path.dirname(target)
  await mkdir(tasksDir, { recursive: true })
  const json = `${JSON.stringify(document, null, 2)}\n`
  await writeFile(target, json, { encoding: 'utf8' })
  return { path: target, json }
}

function buildStep(step, index, capabilities) {
  if (!isPlainObject(step) || !STEP_TYPES.has(step.type)) {
    throw new TypeError(`steps[${index}].type is unsupported`)
  }
  const type = step.type
  let params
  switch (type) {
    case 'StartUp':
      assertFields(step, new Set([...COMMON_FIELDS, 'clientType']))
      params = {
        client_type: enumValue(step.clientType ?? 'Official', CLIENTS, `${type}.clientType`),
        start_game_enabled: true,
      }
      break
    case 'Fight':
      assertFields(step, new Set([...COMMON_FIELDS, 'stage', 'times', 'medicine', 'expiringMedicine', 'stone', 'drops']))
      const fightDrops = dropTargets(step.drops)
      // With a drop target MAA stops as soon as any target is reached, so a
      // missing times means "until the target or the resource limits".
      const fightTimes = step.times === undefined && fightDrops ? 100 : integer(step.times, 1, 100, 'Fight.times')
      params = compact({
        stage: optionalString(fightStage(step.stage), 1, 48, /^[\p{L}\p{N}@._-]+$/u, 'Fight.stage'),
        times: fightTimes,
        medicine: optionalInteger(step.medicine, 0, 99, 'Fight.medicine', 0),
        expiring_medicine: optionalInteger(step.expiringMedicine, 0, 99, 'Fight.expiringMedicine', 0),
        stone: optionalInteger(step.stone, 0, 20, 'Fight.stone', 0),
        // One in-game multi-battle whenever possible. Current MaaCore accepts
        // 1-10; for larger totals, AUTO (0) chooses the stage maximum and then
        // reduces the final group so the requested total is still reached.
        series: fightTimes <= 10 ? fightTimes : 0,
        drops: fightDrops,
      })
      break
    case 'Infrast':
      assertFields(step, new Set([...COMMON_FIELDS, 'mode', 'facilities', 'drones', 'threshold', 'replenish', 'dormNotStationed', 'dormTrust', 'filename', 'planIndex']))
      params = {
        mode: optionalInteger(step.mode, 0, 20000, 'Infrast.mode', 0, new Set([0, 10000, 20000])),
        facility: enumArray(step.facilities ?? [...FACILITIES], FACILITIES, 'Infrast.facilities'),
        drones: enumValue(step.drones ?? '_NotUse', DRONES, 'Infrast.drones'),
        threshold: optionalNumber(step.threshold, 0, 1, 'Infrast.threshold', 0.3),
        replenish: optionalBoolean(step.replenish, false),
        dorm_notstationed_enabled: optionalBoolean(step.dormNotStationed, false),
        dorm_trust_enabled: optionalBoolean(step.dormTrust, false),
      }
      if (params.mode === 10000) {
        params.filename = generatedFile(step.filename, 'Infrast.filename')
        params.plan_index = optionalInteger(step.planIndex, 0, 999, 'Infrast.planIndex', 0)
      } else if (step.filename !== undefined || step.planIndex !== undefined) {
        throw new TypeError('Infrast.filename/planIndex are only valid with mode 10000')
      }
      break
    case 'Recruit':
      assertFields(step, new Set([...COMMON_FIELDS, 'refresh', 'select', 'confirm', 'times', 'setTime', 'expedite', 'permitReserve', 'firstTags', 'extraTagsMode']))
      params = {
        refresh: optionalBoolean(step.refresh, false),
        select: starArray(step.select ?? [4, 5, 6], 'Recruit.select'),
        // MaaCore only presses "confirm" for the listed star levels; an empty
        // list means calculate only. Default to MAA GUI's 3★/4★ so high-star
        // combinations are left untouched for the player.
        confirm: starArray(step.confirm ?? [3, 4], 'Recruit.confirm'),
        times: optionalInteger(step.times, 0, 4, 'Recruit.times', 4),
        set_time: optionalBoolean(step.setTime, true),
        expedite: optionalBoolean(step.expedite, false),
        level3_recruitment_permit_reserve: optionalInteger(step.permitReserve, 0, 999, 'Recruit.permitReserve', 0),
        first_tags: stringArray(step.firstTags ?? [], 10, 24, 'Recruit.firstTags'),
        extra_tags_mode: optionalInteger(step.extraTagsMode, 0, 2, 'Recruit.extraTagsMode', 0),
      }
      break
    case 'Mall':
      assertFields(step, new Set([...COMMON_FIELDS, 'shopping', 'buyFirst', 'blacklist', 'forceShoppingIfCreditFull', 'onlyBuyDiscount', 'reserveMaxCredit', 'visitFriends', 'creditFight']))
      params = {
        shopping: optionalBoolean(step.shopping, false),
        buy_first: stringArray(step.buyFirst ?? [], 20, 32, 'Mall.buyFirst'),
        blacklist: stringArray(step.blacklist ?? [], 20, 32, 'Mall.blacklist'),
        force_shopping_if_credit_full: optionalBoolean(step.forceShoppingIfCreditFull, false),
        only_buy_discount: optionalBoolean(step.onlyBuyDiscount, false),
        reserve_max_credit: optionalBoolean(step.reserveMaxCredit, false),
        visit_friends: optionalBoolean(step.visitFriends, false),
        credit_fight: optionalBoolean(step.creditFight, false),
      }
      break
    case 'Award':
      assertFields(step, new Set([...COMMON_FIELDS, 'dailyWeekly', 'mail', 'freePull', 'orundum', 'mining', 'specialAccess', 'signInEvent']))
      params = {
        award: optionalBoolean(step.dailyWeekly, true),
        mail: optionalBoolean(step.mail, false),
        recruit: optionalBoolean(step.freePull, false),
        orundum: optionalBoolean(step.orundum, false),
        mining: optionalBoolean(step.mining, false),
        specialaccess: optionalBoolean(step.specialAccess, false),
        signinevent: optionalBoolean(step.signInEvent, false),
      }
      break
    case 'Roguelike':
      assertFields(step, new Set([...COMMON_FIELDS, 'theme', 'mode', 'squad', 'coreChar', 'roles', 'startsCount', 'difficulty', 'useSupport', 'useNonFriendSupport', 'stopAtFinalBoss']))
      const effectiveTheme = step.theme ?? capabilities?.roguelike?.themes?.[0]?.id
      const themeCapability = findRoguelikeTheme(capabilities, effectiveTheme)
      if (!themeCapability) throw new TypeError(`Roguelike.theme is invalid for the current MAA resources: ${effectiveTheme ?? '(empty)'}`)
      const modes = new Set(themeCapability.modes.map(item => item.value))
      params = compact({
        theme: effectiveTheme,
        mode: optionalInteger(step.mode, 0, 99999, 'Roguelike.mode', 0, modes),
        squad: optionalString(step.squad, 1, 32, null, 'Roguelike.squad'),
        core_char: optionalString(step.coreChar, 1, 32, null, 'Roguelike.coreChar'),
        roles: optionalString(step.roles, 1, 32, null, 'Roguelike.roles'),
        starts_count: integer(step.startsCount, 1, 99999, 'Roguelike.startsCount'),
        difficulty: optionalInteger(step.difficulty, 0, Math.max(...themeCapability.difficulties, 0), 'Roguelike.difficulty'),
        use_support: optionalBoolean(step.useSupport, false),
        use_nonfriend_support: optionalBoolean(step.useNonFriendSupport, false),
        stop_at_final_boss: optionalBoolean(step.stopAtFinalBoss, false),
      })
      break
    case 'ReclamationAlgorithm':
      assertFields(step, new Set([...COMMON_FIELDS, 'theme', 'mode', 'toolToCraft', 'toolsToCraft', 'numCraftBatches', 'incrementMode', 'clearStore']))
      params = {
        theme: enumValue(step.theme ?? 'Tales', new Set(['Tales', 'RelaunchAnchor']), 'ReclamationAlgorithm.theme'),
        mode: optionalInteger(step.mode, 0, 48, 'ReclamationAlgorithm.mode', 0, new Set([0, 1, 16, 32, 48])),
        tools_to_craft: stringArray(step.toolsToCraft ?? (step.toolToCraft ? [step.toolToCraft] : []), 10, 32, 'ReclamationAlgorithm.toolsToCraft'),
        num_craft_batches: optionalInteger(step.numCraftBatches, 1, 16, 'ReclamationAlgorithm.numCraftBatches', 16),
        increment_mode: optionalInteger(step.incrementMode, 0, 1, 'ReclamationAlgorithm.incrementMode', 0),
        clear_store: optionalBoolean(step.clearStore, false),
      }
      break
    case 'Custom':
      assertFields(step, new Set([...COMMON_FIELDS, 'taskNames']))
      params = { task_names: stringArray(step.taskNames, 20, 96, 'Custom.taskNames', /^[\p{L}\p{N}@:_./-]+$/u) }
      if (params.task_names.length === 0) throw new TypeError('Custom.taskNames cannot be empty')
      break
    case 'Copilot':
      assertFields(step, new Set([...COMMON_FIELDS, 'filename', 'stageName', 'isRaid', 'formation', 'formationIndex', 'addTrust', 'ignoreRequirements', 'supportUnitUsage', 'loopTimes', 'useSanityPotion']))
      {
        const filename = generatedFile(step.filename, 'Copilot.filename')
        const stageName = optionalString(step.stageName, 1, 48, /^[\p{L}\p{N}@._-]+$/u, 'Copilot.stageName')
        params = compact({
          // With a stage name MaaCore navigates to the stage itself; otherwise
          // the job runs on the stage the game currently shows.
          ...(stageName
            ? { copilot_list: [{ filename, stage_name: stageName, is_raid: optionalBoolean(step.isRaid, false) }] }
            : { filename, loop_times: optionalInteger(step.loopTimes, 1, 99, 'Copilot.loopTimes', 1) }),
          formation: optionalBoolean(step.formation, true),
          formation_index: optionalInteger(step.formationIndex, 0, 4, 'Copilot.formationIndex', 0),
          add_trust: optionalBoolean(step.addTrust, false),
          ignore_requirements: optionalBoolean(step.ignoreRequirements, false),
          support_unit_usage: optionalInteger(step.supportUnitUsage, 0, 3, 'Copilot.supportUnitUsage', 0),
          use_sanity_potion: optionalBoolean(step.useSanityPotion, false),
        })
      }
      break
    case 'SSSCopilot':
      assertFields(step, new Set([...COMMON_FIELDS, 'filename', 'loopTimes']))
      params = { filename: generatedFile(step.filename, 'SSSCopilot.filename'), loop_times: optionalInteger(step.loopTimes, 1, 99, 'SSSCopilot.loopTimes', 1) }
      break
    case 'Depot':
    case 'OperBox':
    case 'CloseDown':
      assertFields(step, COMMON_FIELDS)
      break
  }
  return params === undefined ? { type } : { type, params }
}

function summarizeStep(step, capabilities, context = {}) {
  switch (step.type) {
    case 'StartUp': return `启动游戏(${step.clientType ?? 'Official'})`
    case 'Fight': {
      const stage = fightStage(step.stage)
      const times = step.times ?? (step.drops ? 100 : step.times)
      const label = stage === 'Annihilation' ? '剿灭作战' : stage ?? '当前关卡'
      const drops = step.drops && typeof step.drops === 'object' ? `，掉落目标 ${Object.entries(step.drops).map(([item, count]) => `${context.itemIndex?.byId?.get(item)?.name ?? item}×${count}`).join('、')}（任一达到即停）` : ''
      return `作战 ${label} ×${times}${step.drops && step.times === undefined ? '（上限）' : ''}，连战${times <= 10 ? times : '自动分组'}，理智药${step.medicine ?? 0}，临期药${step.expiringMedicine ?? 0}，源石${step.stone ?? 0}${drops}`
    }
    case 'Infrast': return step.mode === 10000 ? `基建自定义排班（方案 ${step.planIndex ?? 0}）` : `基建换班${step.drones && step.drones !== '_NotUse' ? `，无人机=${step.drones}` : ''}`
    case 'Recruit': return recruitSummary(step.times ?? 4, Array.isArray(step.confirm) ? step.confirm : [3, 4], step.expedite === true)
    case 'Copilot': return `自动战斗作业${step.stageName ? ` ${step.stageName}` : ''}${step.formation === false ? '' : '（自动编队）'}`
    case 'SSSCopilot': return `保全派驻作业 ×${step.loopTimes ?? 1}`
    case 'Mall': return `信用商店${step.shopping ? '并购物' : '仅收取/访问'}${step.forceShoppingIfCreditFull ? '，信用溢出时忽略黑名单' : ''}`
    case 'Award': return '领取指定奖励'
    case 'Roguelike': {
      const theme = findRoguelikeTheme(capabilities, step.theme) ?? capabilities?.roguelike?.themes?.[0]
      return `肉鸽 ${theme?.label ?? step.theme ?? '当前默认主题'} ×${step.startsCount}`
    }
    case 'ReclamationAlgorithm': return `生息演算 mode=${step.mode ?? 1}`
    case 'Depot': return '识别仓库'
    case 'OperBox': return '识别干员列表'
    case 'Custom': return `MaaCore任务链 ${step.taskNames?.join(', ')}`
    case 'CloseDown': return '关闭游戏'
    default: return String(step.type)
  }
}

export function recruitSummary(times, confirm, expedite) {
  if (times === 0) return '公招只识别 Tag，不招募'
  if (confirm.length === 0) return `公招${times}次，⚠ 未选择任何自动确认星级，MAA 只会识别、不会招募`
  const stars = [...confirm].sort((a, b) => a - b)
  const high = stars.filter(star => star >= 5)
  return `公招${times}次，自动确认 ${stars.join('/')}★${expedite ? '，使用加急许可' : ''}${high.length ? `，⚠ ${high.join('/')}★ 也会自动确认` : '；5★/6★ 组合不确认，留给你手动处理'}`
}

function fightStage(value) {
  if (typeof value !== 'string') return value
  const trimmed = value.trim()
  return STAGE_ALIASES.get(trimmed) ?? STAGE_ALIASES.get(trimmed.toLowerCase()) ?? trimmed
}
function dropTargets(value) {
  if (value === undefined) return undefined
  if (!isPlainObject(value)) throw new TypeError('Fight.drops must map MAA item ids to quantities')
  const entries = Object.entries(value)
  if (entries.length === 0) return undefined
  if (entries.length > 10) throw new TypeError('Fight.drops supports at most 10 items')
  return Object.fromEntries(entries.map(([id, count]) => {
    if (!ITEM_ID_PATTERN.test(id)) throw new TypeError(`Fight.drops item id is invalid: ${id}`)
    return [id, integer(count, 1, 99999, `Fight.drops.${id}`)]
  }))
}
function generatedFile(value, label) {
  if (typeof value !== 'string' || !GENERATED_FILE_PATTERN.test(value)) throw new TypeError(`${label} must be a file generated by this plugin`)
  return value
}
function assertFields(object, allowed) { for (const key of Object.keys(object)) if (!allowed.has(key)) throw new TypeError(`${object.type}.${key} is not supported`) }
function compact(object) { return Object.fromEntries(Object.entries(object).filter(([, value]) => value !== undefined)) }
function isPlainObject(value) { return value !== null && typeof value === 'object' && !Array.isArray(value) }
function enumValue(value, allowed, label) { if (!allowed.has(value)) throw new TypeError(`${label} is invalid`); return value }
function enumArray(value, allowed, label) { if (!Array.isArray(value) || value.length === 0 || value.some(item => !allowed.has(item))) throw new TypeError(`${label} contains an invalid value`); return [...new Set(value)] }
function integer(value, min, max, label) { if (!Number.isInteger(value) || value < min || value > max) throw new TypeError(`${label} must be an integer from ${min} to ${max}`); return value }
function optionalInteger(value, min, max, label, fallback, discrete) { if (value === undefined) return fallback; const result = integer(value, min, max, label); if (discrete && !discrete.has(result)) throw new TypeError(`${label} is invalid`); return result }
function optionalNumber(value, min, max, label, fallback) { if (value === undefined) return fallback; if (typeof value !== 'number' || !Number.isFinite(value) || value < min || value > max) throw new TypeError(`${label} must be from ${min} to ${max}`); return value }
function optionalBoolean(value, fallback) { if (value === undefined) return fallback; if (typeof value !== 'boolean') throw new TypeError('expected a boolean'); return value }
function optionalString(value, min, max, pattern, label) { if (value === undefined) return undefined; if (typeof value !== 'string' || value.length < min || value.length > max || (pattern && !pattern.test(value))) throw new TypeError(`${label} is invalid`); return value }
function stringArray(value, maxItems, maxLength, label, pattern) { if (!Array.isArray(value) || value.length > maxItems) throw new TypeError(`${label} must be an array with at most ${maxItems} items`); return value.map((item, index) => optionalString(item, 1, maxLength, pattern ?? null, `${label}[${index}]`)) }
function starArray(value, label) { if (!Array.isArray(value) || value.some(star => !Number.isInteger(star) || star < 1 || star > 6)) throw new TypeError(`${label} must contain star levels from 1 to 6`); return [...new Set(value)] }
